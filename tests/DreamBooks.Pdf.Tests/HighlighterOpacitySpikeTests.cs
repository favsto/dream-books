using System.Globalization;
using System.Runtime.InteropServices;
using System.Text;
using System.Text.RegularExpressions;
using DreamBooks.Pdf.Interop;
using static DreamBooks.Pdf.Tests.TextPdfFactory;

namespace DreamBooks.Pdf.Tests;

/// <summary>
/// The phase 3c opacity spike (FR-40), kept as the regression of the highlighter write route
/// (<see cref="HighlighterWriteRoute"/>; notes in docs/superpowers/specs/2026-11-02-phase3c-opacity-spike-notes.md).
/// A page with a dark text line gets one highlight ink annotation in #FFE14D with colour alpha 89, written with the
/// StrokeAnnotations call order; the file is saved (full rewrite), reopened in a fresh PDFium instance as another
/// reader would, and rendered at 200 %. The text under the highlight is compared with the same word outside it.
/// </summary>
public sealed partial class HighlighterOpacitySpikeTests : IDisposable
{
    private const double _pageWidth = 300;
    private const double _pageHeight = 200;
    private const double _scale = 2;
    private const double _fontSize = 24;
    private const double _textX = 20;
    private const double _baseline = 90;
    private const double _xHeight = 0.523 * _fontSize; // Helvetica
    private const string _word = "mmmmmm";

    // Highlight band over the first word only (user space, y up).
    private const double _bandLeft = 10;
    private const double _bandRight = 140;
    private const double _bandBottom = 81;
    private const double _bandTop = 111;

    // Columns covered by every variant (route B's band ends at the centreline's ends: butt caps).
    private const double _underLeft = 30;
    private const double _underRight = 120;

    private const byte _red = 0xFF;
    private const byte _green = 0xE1;
    private const byte _blue = 0x4D;
    private const byte _alpha = 89; // HighlighterAlpha, 0.35

    private readonly string _dir;

    public HighlighterOpacitySpikeTests()
    {
        _dir = Path.Combine(Path.GetTempPath(), "DreamBooks.Pdf.Tests", Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(_dir);
    }

    public void Dispose()
    {
        try
        {
            Directory.Delete(_dir, recursive: true);
        }
        catch (IOException)
        {
        }
    }

    [Fact]
    public void The_chosen_route_is_our_custom_appearance() => // FR-40, FR-46
        Assert.Equal(HighlighterWriteRoute.Route.CustomAppearance, HighlighterWriteRoute.Current);

    [Fact]
    public async Task Route_A_appearance_that_selects_the_GS_state_is_translucent_and_keeps_CA() // FR-40
    {
        string saved = await AuthorAsync(Variant.AppearanceSelectingGs);

        AssertCa(saved);
        Assert.Contains("/ExtGState", Latin1(saved), StringComparison.Ordinal);
        AssertTranslucent(await MeasureAsync(saved));
    }

    [Fact]
    public async Task Route_A_appearance_without_the_GS_operator_renders_opaque() // FR-40 pitfall
    {
        // PDFium does not apply the annotation's /CA to an appearance stream by itself: the ExtGState that
        // SetAP adds under /Resources is applied only when the content selects it with "/GS gs".
        string saved = await AuthorAsync(Variant.AppearanceWithoutGs);

        AssertCa(saved);
        Measurement m = await MeasureAsync(saved);
        Assert.InRange(m.BandBlue, _blue - 3, _blue + 3);
        Assert.True(m.GlyphUnderLuminance > 200, $"glyph under the highlight {m.GlyphUnderLuminance:0.0}");
    }

    [Fact]
    public async Task Route_B_pdfium_generated_appearance_is_translucent_and_keeps_CA() // FR-40
    {
        string saved = await AuthorAsync(Variant.PdfiumGenerated);

        AssertCa(saved);
        Assert.DoesNotContain("/AP", Latin1(saved), StringComparison.Ordinal); // generated by the reader
        AssertTranslucent(await MeasureAsync(saved));
    }

    private static string Latin1(string path) => Encoding.Latin1.GetString(File.ReadAllBytes(path));

    private static void AssertCa(string saved)
    {
        Match match = CaPattern().Match(Latin1(saved));
        Assert.True(match.Success, "the annotation dictionary has no /CA");
        double ca = double.Parse(match.Groups[1].Value, CultureInfo.InvariantCulture);
        Assert.InRange(ca, 0.345, 0.355);
    }

    private static void AssertTranslucent(Measurement m)
    {
        // The band is drawn and translucent: 0.35 of #FFE14D over white gives blue ~193; an opaque fill gives 77.
        Assert.InRange(m.BandBlue, 180, 205);

        // The text under the highlight stays dark: 0.35 of the yellow over black, far below the tinted paper.
        Assert.True(m.GlyphUnderLuminance < m.BandLuminance * 0.5,
            $"glyph under the highlight {m.GlyphUnderLuminance:0.0}, band {m.BandLuminance:0.0}");
        Assert.True(m.GlyphOutsideLuminance < 30, $"glyph outside {m.GlyphOutsideLuminance:0.0}");
    }

    private async Task<string> AuthorAsync(Variant variant)
    {
        string source = Path.Combine(_dir, $"{Guid.NewGuid():N}.pdf");
        Write(source, new TextPageSpec(
            _pageWidth,
            _pageHeight,
            [new TextLine(_textX, _baseline, _word), new TextLine(SecondWordX, _baseline, _word)],
            FontSize: _fontSize));

        string saved = Path.Combine(_dir, $"{Guid.NewGuid():N}.pdf");
        await PdfiumThread.RunAsync(
            () =>
            {
                using var document = PdfiumDocument.Open(source);
                nint page = document.LoadPage(0);
                try
                {
                    nint annot = PdfiumNative.FPDFPage_CreateAnnot(page, PdfiumNative.FPDF_ANNOT_INK);
                    Assert.NotEqual(0, annot);
                    try
                    {
                        WriteHighlight(annot, variant);
                    }
                    finally
                    {
                        PdfiumNative.FPDFPage_CloseAnnot(annot);
                    }

                    document.SaveFullRewrite(saved);
                }
                finally
                {
                    document.ClosePage(page);
                }
            },
            CancellationToken.None);
        return saved;
    }

    private static double SecondWordX => _textX + Width(_word + " ", _fontSize);

    /// <summary>The StrokeAnnotations order: Rect, Color, Border, InkList, Flags, then SetAP (route A only).</summary>
    private static void WriteHighlight(nint annot, Variant variant)
    {
        double half = (_bandTop - _bandBottom) / 2;
        double mid = (_bandTop + _bandBottom) / 2;
        var rect = new PdfiumNative.FS_RECTF
        {
            Left = (float)_bandLeft - 1,
            Bottom = (float)_bandBottom - 1,
            Right = (float)_bandRight + 1,
            Top = (float)_bandTop + 1,
        };
        Assert.NotEqual(0, NativeSetRect(annot, ref rect));
        Assert.NotEqual(0, PdfiumNative.FPDFAnnot_SetColor(
            annot, PdfiumNative.FPDFANNOT_COLORTYPE_Color, _red, _green, _blue, _alpha));

        // Route B: the border width is the highlight width (PDFium draws it with butt caps).
        bool generated = variant == Variant.PdfiumGenerated;
        Assert.NotEqual(0, PdfiumNative.FPDFAnnot_SetBorder(annot, 0, 0, generated ? (float)(half * 2) : 1));
        PdfiumNative.FS_POINTF[] centreline = generated
            ? [Point(_bandLeft + half, mid), Point((_bandLeft + _bandRight) / 2, mid), Point(_bandRight - half, mid)]
            : [Point(_bandLeft, mid), Point(_bandRight, mid)];
        Assert.True(NativeAddInkStroke(annot, centreline, (nuint)centreline.Length) >= 0);
        Assert.NotEqual(0, PdfiumNative.FPDFAnnot_SetFlags(annot, PdfiumNative.FPDF_ANNOT_FLAG_PRINT));

        if (!generated)
        {
            // A filled contour in several path segments in the fill colour, as the stroke writer builds it.
            string gs = variant == Variant.AppearanceSelectingGs ? "/GS gs\n" : string.Empty;
            string content = string.Create(CultureInfo.InvariantCulture,
                $"{gs}1 0.8824 0.302 rg\n{_bandLeft} {_bandBottom} m\n{mid} {_bandBottom} l\n{_bandRight} {_bandBottom} l\n"
                + $"{_bandRight} {_bandTop} l\n{mid} {_bandTop} l\n{_bandLeft} {_bandTop} l\nh\nf");
            Assert.True(PdfiumAnnotations.SetAppearance(annot, content));
        }
    }

    private static async Task<Measurement> MeasureAsync(string saved)
    {
        await using var renderer = await PdfRenderer.OpenAsync(saved);
        RenderedPage page = await renderer.RenderPageAsync(0, (int)(_pageWidth * _scale), (int)(_pageHeight * _scale));

        static int Px(double x) => (int)Math.Round(x * _scale);
        static int Py(double y) => (int)Math.Round((_pageHeight - y) * _scale);

        // Glyph rows: baseline to x-height, inset by one point; the same columns under and outside the band.
        int glyphTop = Py(_baseline + _xHeight - 1);
        int glyphBottom = Py(_baseline + 1);
        double outsideLeft = SecondWordX + (_underLeft - _textX);
        double outsideRight = SecondWordX + (_underRight - _textX);
        double glyphUnder = MinLuminance(page, Px(_underLeft), glyphTop, Px(_underRight), glyphBottom);
        double glyphOutside = MinLuminance(page, Px(outsideLeft), glyphTop, Px(outsideRight), glyphBottom);

        // Band rows above the glyphs, inside the highlight.
        (double bandLum, double bandBlue) =
            Average(page, Px(_underLeft), Py(_bandTop - 2), Px(_underRight), Py(_baseline + _xHeight + 2));

        return new Measurement(glyphUnder, glyphOutside, bandLum, bandBlue);
    }

    private static double Luminance(RenderedPage page, int x, int y)
    {
        int i = (y * page.Stride) + (x * 4);
        return (0.0722 * page.Bgra[i]) + (0.7152 * page.Bgra[i + 1]) + (0.2126 * page.Bgra[i + 2]);
    }

    private static double MinLuminance(RenderedPage page, int left, int top, int right, int bottom)
    {
        double min = double.MaxValue;
        for (int y = top; y < bottom; y++)
        {
            for (int x = left; x < right; x++)
            {
                min = Math.Min(min, Luminance(page, x, y));
            }
        }

        return min;
    }

    private static (double Luminance, double Blue) Average(RenderedPage page, int left, int top, int right, int bottom)
    {
        double lum = 0, blue = 0;
        int n = 0;
        for (int y = top; y < bottom; y++)
        {
            for (int x = left; x < right; x++)
            {
                lum += Luminance(page, x, y);
                blue += page.Bgra[(y * page.Stride) + (x * 4)];
                n++;
            }
        }

        return (lum / n, blue / n);
    }

    private static PdfiumNative.FS_POINTF Point(double x, double y) => new() { X = (float)x, Y = (float)y };

    // PdfiumNative's pointer parameters need unsafe code, which the test project does not enable; these
    // by-reference imports call the same entry points.
    [DllImport(PdfiumNative.Library, EntryPoint = "FPDFAnnot_SetRect")]
    private static extern int NativeSetRect(nint annotation, ref PdfiumNative.FS_RECTF rect);

    [DllImport(PdfiumNative.Library, EntryPoint = "FPDFAnnot_AddInkStroke")]
    private static extern int NativeAddInkStroke(nint annotation, [In] PdfiumNative.FS_POINTF[] points, nuint count);

    [GeneratedRegex(@"/CA\s*([0-9]*\.?[0-9]+)")]
    private static partial Regex CaPattern();

    private enum Variant
    {
        AppearanceWithoutGs,
        AppearanceSelectingGs,
        PdfiumGenerated,
    }

    private sealed record Measurement(
        double GlyphUnderLuminance, double GlyphOutsideLuminance, double BandLuminance, double BandBlue);
}
